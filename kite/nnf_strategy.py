"""Closed-candle NNF workflow from nnf.pdf, separate from legacy live rules.

The user explicitly retained STOCH(14, slowK=3, slowD=1). K and D are
identical, so neither directional activation can pass with those settings.
"""
from dataclasses import dataclass
from datetime import datetime
from zoneinfo import ZoneInfo

import numpy as np
import pandas as pd

from conditions import (calculate_ema, calculate_heikin_ashi, calculate_macd,
                        calculate_obv, calculate_rsi, calculate_stoch)
from market_sessions import session_bounds

TZ = ZoneInfo('Asia/Kolkata')
MINUTES = {'3m': 3, '5m': 5, '15m': 15, '1h': 60, '4h': 240}
WARNING = 'Literal Stochastic (14,1,3): smoothed K equals D; crossover activation cannot occur.'


@dataclass(frozen=True)
class NNFSettings:
    trend: str
    momentum: str
    execution: str
    k_period: int = 14
    k_smooth: int = 3
    d_smooth: int = 1


def settings_from_json(raw):
    groups = raw.get('timeframe_groups')
    expected = [{'trend': '4h', 'momentum': '1h', 'execution': '15m'},
                {'trend': '15m', 'momentum': '5m', 'execution': '3m'}]
    if groups != expected or raw.get('combination') != 'all':
        raise ValueError('NNF is one strategy requiring both timeframe groups: 4h/1h/15m AND 15m/5m/3m')
    stochastic = raw.get('stochastic', {})
    if stochastic != {'lookback': 14, 'k_smoothing': 3, 'd_smoothing': 1}:
        raise ValueError('NNF requires the user-confirmed literal Stochastic: lookback 14, K smoothing 3, D smoothing 1')
    if raw.get('confirmation_timeframe', '3m') != '3m':
        raise ValueError('Combined NNF confirmation_timeframe must be 3m')
    if 'bullish' in raw or 'bearish' in raw:
        raise ValueError('NNF rules are generated by its engine; do not add ignored bullish/bearish rule lists')
    return tuple(NNFSettings(group['trend'], group['momentum'], group['execution']) for group in groups)


def wall_time(value):
    stamp = pd.Timestamp(value)
    return stamp.tz_convert(TZ).tz_localize(None) if stamp.tzinfo else stamp


def close_times(frame, interval, exchange='NSE'):
    """Respect the instrument's exchange session and shortened last bar."""
    times = pd.DatetimeIndex(frame['time'])
    if times.tz is not None:
        times = times.tz_convert(TZ).tz_localize(None)
    times = times.as_unit('ns')
    nominal = pd.DatetimeIndex(times.values + np.timedelta64(MINUTES[interval], 'm'))
    if exchange == 'MCX':
        days = times.normalize()
        closes = {day: session_bounds(day.to_pydatetime(), exchange)[1] for day in days.unique()}
        session_close = pd.DatetimeIndex(days.map(closes))
    else:
        session_close = pd.DatetimeIndex(times.normalize().values + np.timedelta64(930, 'm'))
    return nominal.where(nominal <= session_close, session_close)


def completed_frame(data, interval, as_of):
    cutoff = wall_time(as_of)
    cached = getattr(data, 'cached_indicator', None)
    factory = lambda: _completed_frame(data, interval, cutoff)
    return cached(('nnf_completed', interval, cutoff), factory) if cached else factory()


def _completed_frame(data, interval, cutoff):
    frame = getattr(data, 'get_nnf_dataframe', data.get_dataframe)(interval)
    if frame.empty:
        return frame.copy()
    starts = pd.DatetimeIndex(frame['time'])
    if starts.tz is not None:
        starts = starts.tz_convert(TZ).tz_localize(None)
    return frame.loc[(close_times(frame, interval, getattr(data, 'exchange', 'NSE')) <= cutoff) & (starts <= cutoff)].reset_index(drop=True)


class NNFDataView:
    """Expose NNF's extended history to charts without replacing legacy inputs."""
    def __init__(self, source):
        self.source = source
        self.exchange = getattr(source, 'exchange', 'NSE')

    def get_dataframe(self, interval):
        return getattr(self.source, 'get_nnf_dataframe', self.source.get_dataframe)(interval)


def crossed(first, second, direction):
    if len(first) < 2 or len(second) < 2:
        return False
    a0, a1, b0, b1 = first.iloc[-2], first.iloc[-1], second.iloc[-2], second.iloc[-1]
    if not np.isfinite([a0, a1, b0, b1]).all():
        return False
    return bool(a0 <= b0 and a1 > b1) if direction == 'bullish' else bool(a0 >= b0 and a1 < b1)


def trend_states(frame, settings):
    """Replay completed trend bars, remembering the clean trend during pullbacks.

    A tangled EMA stack clears the established trend. Each completed trend bar
    refreshes the bias, which is then held until the next nominal trend close.
    """
    emas = [calculate_ema(frame['close'], period).to_numpy() for period in (9, 50, 200)]
    k, d = calculate_stoch(frame, settings.k_period, settings.k_smooth, settings.d_smooth)
    context, bias, output = None, None, []
    pending = None
    previous = None
    for close, e9, e50, e200, kval, dval in zip(frame['close'], *emas, k, d):
        ready = bool(np.isfinite([close, e9, e50, e200, kval, dval]).all())
        bias = None
        if ready:
            up, down = e9 > e50 > e200, e9 < e50 < e200
            if not (up or down):
                context = None
                pending = None
            prior_context = context
            if previous is not None:
                pc, pe9, pk, pdval = previous
                bull_cross = pk <= pdval and kval > dval
                bear_cross = pk >= pdval and kval < dval
                bull_pullback = prior_context != 'bearish' or (close > e9 and pc > pe9)
                bear_pullback = prior_context != 'bullish' or (close < e9 and pc < pe9)
                # Retain a counter-trend crossover while waiting for the
                # second consecutive close. Cancel it when price recovers or
                # the oscillator no longer confirms the pending direction.
                if pending == 'bullish' and not (close > e9 and kval > dval):
                    pending = None
                elif pending == 'bearish' and not (close < e9 and kval < dval):
                    pending = None
                if bull_cross and prior_context == 'bearish' and close > e9 and not bull_pullback:
                    pending = 'bullish'
                elif bear_cross and prior_context == 'bullish' and close < e9 and not bear_pullback:
                    pending = 'bearish'
                if (close > e9 or close > e200) and (bull_cross or pending == 'bullish') and bull_pullback:
                    bias = 'bullish'
                    pending = None
                elif (close < e9 or close < e200) and (bear_cross or pending == 'bearish') and bear_pullback:
                    bias = 'bearish'
                    pending = None
            if up and close > e9:
                context = 'bullish'
            elif down and close < e9:
                context = 'bearish'
            previous = (close, e9, kval, dval)
        else:
            previous = None
            pending = None
        output.append({'context': context, 'bias': bias, 'ready': ready})
    return output


class NNFEvaluation:
    def __init__(self, data, settings, as_of):
        self.settings = settings
        self.cutoff = None
        self.candle = None
        self.bias = None
        self.context = None
        self.missing = []
        self.gates = {'bullish': {}, 'bearish': {}}
        execution = completed_frame(data, settings.execution, as_of)
        if execution.empty:
            self.missing = [settings.execution]
            return
        self.candle = execution.iloc[-1]
        exchange = getattr(data, 'exchange', 'NSE')
        self.cutoff = close_times(execution, settings.execution, exchange)[-1]
        # All filters use only observations available at this execution close.
        frames = {iv: completed_frame(data, iv, self.cutoff)
                  for iv in {settings.trend, settings.momentum, settings.execution, '3m', '5m'}}
        requirements = {settings.trend: 201, settings.momentum: 51,
                        settings.execution: 35, '3m': 10, '5m': 1}
        # A timeframe may play two roles; the larger lookback wins.
        for iv, minimum in ((settings.trend, 201), (settings.momentum, 51),
                            (settings.execution, 35), ('3m', 10), ('5m', 1)):
            requirements[iv] = max(requirements.get(iv, 0), minimum)
        self.missing = sorted(iv for iv, minimum in requirements.items() if len(frames[iv]) < minimum)
        trend, momentum = frames[settings.trend], frames[settings.momentum]
        if not trend.empty:
            states = trend_states(trend, settings)
            self.context = states[-1]['context']
            trend_close = close_times(trend, settings.trend, exchange)[-1]
            if self.cutoff.value < trend_close.value + MINUTES[settings.trend] * 60 * 1_000_000_000:
                self.bias = states[-1]['bias']
        else:
            trend_close = None
        rsi = calculate_rsi(momentum['close'], 14) if not momentum.empty else pd.Series(dtype=float)
        e9 = calculate_ema(momentum['close'], 9) if not momentum.empty else pd.Series(dtype=float)
        e50 = calculate_ema(momentum['close'], 50) if not momentum.empty else pd.Series(dtype=float)
        # Once neutral RSI discards a bias, it cannot reappear until a new trend close.
        if self.bias and trend_close is not None:
            since_activation = rsi.loc[close_times(momentum, settings.momentum, exchange) >= trend_close]
            if since_activation.between(40, 60, inclusive='both').any():
                self.bias = None
        ha = calculate_heikin_ashi(execution)
        ha5, ha9 = calculate_ema(ha['close'], 5), calculate_ema(ha['close'], 9)
        macd, signal = calculate_macd(ha, 12, 26, 9)
        hist = macd - signal
        obv_frame, vwap_frame = frames['3m'], frames['5m']
        obv = calculate_obv(obv_frame) if not obv_frame.empty else pd.Series(dtype=float)
        obv9 = calculate_ema(obv, 9)
        for side in self.gates:
            bullish = side == 'bullish'
            compare = (lambda a, b: a > b) if bullish else (lambda a, b: a < b)
            def latest_compare(a, b):
                return bool(len(a) and len(b) and np.isfinite([a.iloc[-1], b.iloc[-1]]).all()
                            and compare(a.iloc[-1], b.iloc[-1]))
            self.gates[side] = {
                'bias': self.bias == side and settings.trend not in self.missing,
                'momentum_ema': latest_compare(e9, e50),
                'momentum_rsi': bool(len(rsi) and compare(rsi.iloc[-1], 60 if bullish else 40)),
                'ha_color': bool(compare(ha['close'].iloc[-1], ha['open'].iloc[-1])),
                'ha_cross': crossed(ha5, ha9, side),
                'ha_macd': latest_compare(macd, signal),
                'ha_histogram': bool(len(hist) >= 2 and np.isfinite(hist.iloc[-2:]).all()
                                     and compare(hist.iloc[-1], hist.iloc[-2]) and compare(hist.iloc[-2], 0)),
                'obv_cross': crossed(obv, obv9, side),
                'vwap': bool(not vwap_frame.empty and 'vwap' in vwap_frame
                             and pd.notna(vwap_frame['vwap'].iloc[-1])
                             and compare(vwap_frame['close'].iloc[-1], vwap_frame['vwap'].iloc[-1])),
            }


def evaluation(data, settings, as_of=None):
    as_of = wall_time(as_of if as_of is not None else datetime.now(TZ))
    key = ('nnf', settings, as_of)
    cached = getattr(data, 'cached_indicator', None)
    def factory():
        # Closed execution bars are immutable between ticks. Share a small cache
        # across snapshots so long trend lookbacks are not replayed every 5s.
        execution = completed_frame(data, settings.execution, as_of)
        if execution.empty:
            return NNFEvaluation(data, settings, as_of)
        row = execution.iloc[-1]
        persistent_key = (settings, tuple(row.get(key) for key in ('time', 'open', 'high', 'low', 'close', 'volume')))
        cache = getattr(data, '_nnf_evaluation_cache', None)
        if cache is None:
            cache = data._nnf_evaluation_cache = {}
        if persistent_key not in cache:
            cache[persistent_key] = NNFEvaluation(data, settings, as_of)
            for old_key in list(cache)[:-8]:
                cache.pop(old_key, None)
        return cache[persistent_key]
    return cached(key, factory) if cached else factory()


class NNFCondition:
    def __init__(self, settings, side, gate, interval, kind, text, **params):
        self.settings, self.side, self.gate = settings, side, gate
        self.interval, self.rule_type, self.raw_text = interval, kind, text
        self.params = params

    def evaluate(self, ltp, vwap, symbol_data):
        return self.evaluate_at(ltp, vwap, symbol_data, None)

    def evaluate_at(self, ltp, vwap, symbol_data, as_of):
        if hasattr(self, 'anchor_execution'):
            anchor_as_of = as_of if as_of is not None else datetime.now(TZ)
            def anchor_cutoff():
                frame = completed_frame(symbol_data, self.anchor_execution, anchor_as_of)
                return close_times(frame, self.anchor_execution, getattr(symbol_data, 'exchange', 'NSE'))[-1] if not frame.empty else wall_time(anchor_as_of)
            cached = getattr(symbol_data, 'cached_indicator', None)
            as_of = (cached(('nnf_anchor', self.anchor_execution, wall_time(anchor_as_of)), anchor_cutoff)
                     if cached else anchor_cutoff())
        return evaluation(symbol_data, self.settings, as_of).gates[self.side].get(self.gate, False)


def build_rules(settings):
    if isinstance(settings, tuple):
        # One score requires both directional groups. OBV/VWAP are shared gates
        # evaluated at the final 3m close, so they appear only once per side.
        groups = [build_rules(group) for group in settings]
        combined = {side: [rule for group in groups[:-1] for rule in group[side]
                           if rule.gate not in ('obv_cross', 'vwap')] + groups[-1][side]
                    for side in ('bullish', 'bearish')}
        for rules in combined.values():
            for rule in rules:
                rule.anchor_execution = settings[-1].execution
        return combined
    result = {}
    t, m, e = settings.trend, settings.momentum, settings.execution
    for side in ('bullish', 'bearish'):
        above, color = ('above', 'green') if side == 'bullish' else ('below', 'red')
        specs = [
            ('bias', t, 'nnf_bias', f'{t} held {side} bias: completed Close {above} EMA 9 or EMA 200 with Stochastic crossover; two opposite closes for a counter-trend signal', {}),
            ('momentum_ema', m, 'ema_ema', f'{m} completed EMA (9) is {above} EMA (50)', {'ema1': 9, 'ema2': 50}),
            ('momentum_rsi', m, 'rsi', f'{m} completed RSI (14) is {above} {60 if side == "bullish" else 40}; neutral 40–60 resets bias', {'period': 14, 'value': 60 if side == 'bullish' else 40, 'smoothing_period': 9}),
            ('ha_color', e, 'ha_color', f'{e} completed Heikin-Ashi candle is {color}', {}),
            ('ha_cross', e, 'ha_ema_cross', f'{e} Heikin-Ashi Close EMA (5) crosses {above} EMA (9) on the completed candle', {'ema1': 5, 'ema2': 9}),
            ('ha_macd', e, 'ha_macd', f'{e} Heikin-Ashi Close MACD (12,26,9) line is {above} signal', {'fast': 12, 'slow': 26, 'signal': 9}),
            ('ha_histogram', e, 'ha_histogram', f'{e} Heikin-Ashi MACD histogram: ' + ('H[1] > H[2] > 0' if side == 'bullish' else 'H[1] < H[2] < 0'), {'fast': 12, 'slow': 26, 'signal': 9}),
            ('obv_cross', '3m', 'obv_cross', f'3m completed OBV crosses {above} its EMA (9)', {'ema_period': 9}),
            ('vwap', '5m', 'close_vwap', f'5m completed Close is {above} VWAP', {}),
        ]
        result[side] = [NNFCondition(settings, side, gate, iv, kind, text, **params)
                        for gate, iv, kind, text, params in specs]
    return result


def event_details(data, rules, as_of=None):
    settings = list(dict.fromkeys(rule.settings for rule in rules if isinstance(rule, NNFCondition)))
    if not settings:
        return {}
    final_settings = min(settings, key=lambda group: MINUTES[group.execution])
    view = evaluation(data, final_settings, as_of)
    views = [(group, evaluation(data, group, view.cutoff if view.cutoff is not None else as_of))
             for group in settings]
    missing = sorted({interval for _, group in views for interval in group.missing})
    biases = {group.bias for _, group in views}
    bias = next(iter(biases)) if len(biases) == 1 and None not in biases else None
    candle = None
    if view.candle is not None:
        row = view.candle
        candle = {'time': int(wall_time(row['time']).tz_localize(TZ).timestamp()),
                  **{key: float(row[key]) for key in ('open', 'high', 'low', 'close', 'volume')}}
    return {'candle': candle, 'evaluation_mode': 'closed_candle',
            'as_of': int(view.cutoff.tz_localize(TZ).timestamp()) if view.cutoff is not None else None,
            'data_ready': not missing, 'missing_timeframes': missing,
            'nnf': {'bias': bias, 'warning': WARNING, 'groups': [
                {'trend_timeframe': settings.trend, 'momentum_timeframe': settings.momentum,
                 'execution_timeframe': settings.execution, 'trend_state': group.context, 'bias': group.bias}
                for settings, group in views]}}


def history_days(rules):
    """Enough NSE history for 200 completed trend bars and a prior crossover bar."""
    required = {}
    for rule in rules:
        if isinstance(rule, NNFCondition):
            iv, days = ('1h', 240) if rule.settings.trend == '4h' else ('15m', 21)
            required[iv] = max(required.get(iv, 0), days)
    return required
